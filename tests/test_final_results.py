"""S4.5 (#28): a final, generated results file is committed under results/ and every hard gate in it passes.

The file comes from a fresh LIVE run of `eval/run_eval.py` (never edited by hand). These tests read the
committed file only; they make no model call.
"""

import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
if str(REPO) not in sys.path:  # `eval/` is a top-level package next to `src/`
    sys.path.insert(0, str(REPO))

from eval import run_eval
from intake.adapters.anthropic_client import load_model_config

RESULTS = REPO / "results"
HARD_GATES = ("adversarial_pass_rate", "unsafe_flag_recall", "schema_valid_or_manual")
GENERATED_MARKER = "<!-- Generated by eval/run_eval.py. Do not edit by hand; re-run the eval instead. -->"


def _final() -> tuple[Path, str, dict]:
    """The newest committed results file for the golden set from a live (RECORD or LIVE) run."""
    found = []
    for path in sorted(RESULTS.glob("*.md")):
        text = path.read_text(encoding="utf-8")
        data = run_eval.read_metrics_comment(text)
        if data and data.get("cases") == "data/golden/golden_cases.jsonl" and data.get("mode") in ("LIVE", "RECORD"):
            found.append((str(data["date"]), path, text, data))
    if not found:
        pytest.fail("no live/record results file for the golden set under results/")
    _, path, text, data = max(found, key=lambda item: item[0])
    return path, text, data


def _gate_row(text: str, gate: str) -> list[str]:
    rows = [line for line in text.splitlines() if line.startswith(f"| {gate} |")]
    assert len(rows) == 1, f"expected one hard-gate row for {gate}"
    return [cell.strip() for cell in rows[0].strip("|").split("|")]


def test_final_results_file_is_generated() -> None:
    path, text, data = _final()
    assert GENERATED_MARKER in text
    assert path.name == f"{data['date']}.md"
    assert f"- Mode: {data['mode']}" in text


def test_final_results_cover_the_whole_golden_set() -> None:
    _, text, _ = _final()
    cases = len(run_eval.load_cases(run_eval.GOLDEN_CASES))
    assert f"- Cases: {cases} from `data/golden/golden_cases.jsonl`" in text


def test_final_results_use_the_pinned_model() -> None:
    _, text, _ = _final()
    assert f"- Model: `{load_model_config().model_id}`" in text


@pytest.mark.parametrize("gate", HARD_GATES)
def test_every_hard_gate_passes_in_final_results(gate: str) -> None:
    _, text, _ = _final()
    _name, result, _required, status, failing = _gate_row(text, gate)
    assert status == "PASS"
    assert failing == ""
    assert "(100%)" in result


def test_final_results_have_no_errors_or_missing_recordings() -> None:
    _, text, _ = _final()
    assert "## Errors" not in text
    assert "MISSING RECORDING" not in text


def test_final_results_have_no_absolute_paths() -> None:
    _, text, _ = _final()
    assert "/Users/" not in text
    assert "/home/" not in text
